package schema

import (
	"fmt"
	"slices"
	"sort"
	"strings"
)

// buckets groups the statements of a diff by the order they must run in:
// everything that removes first (foreign keys before the keys they point
// at), then everything that adds (foreign keys last).
type buckets struct {
	dropFK, dropIdx, dropCon, dropCol []string
	addCol, alterCol, addCon, addIdx  []string
	addFK                             []string
}

func (b *buckets) pre() []string {
	return slices.Concat(b.dropFK, b.dropIdx, b.dropCon, b.dropCol)
}

func (b *buckets) post() []string {
	return slices.Concat(b.addCol, b.alterCol, b.addCon, b.addIdx)
}

// diffShared compares the tables present in both snapshots and returns
// what turns from into to.
func diffShared(from, to *snapshot, tables []string) *buckets {
	b := &buckets{}
	for _, name := range tables {
		f, t := from.tables[name], to.tables[name]

		for _, idx := range sortedKeys(f.idx) {
			if t.idx[idx] != f.idx[idx] {
				b.dropIdx = append(b.dropIdx, fmt.Sprintf("DROP INDEX %s;", idx))
			}
		}
		for _, cn := range sortedKeys(f.cons) {
			fc := f.cons[cn]
			if tc := t.cons[cn]; tc != nil && tc.def == fc.def {
				continue
			}
			stmt := fmt.Sprintf("ALTER TABLE %s DROP CONSTRAINT %s;", name, cn)
			if fc.kind == "f" {
				b.dropFK = append(b.dropFK, stmt)
			} else {
				b.dropCon = append(b.dropCon, stmt)
			}
		}

		for _, fc := range f.cols {
			tc := t.byName[fc.name]
			switch {
			case tc == nil:
				b.dropCol = append(b.dropCol, fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s;", name, fc.name))
			case fc.generated != tc.generated || (tc.generated != "" && fc.expr != tc.expr):
				// A generated column is recomputed, so drop + add loses nothing.
				b.dropCol = append(b.dropCol, fmt.Sprintf("ALTER TABLE %s DROP COLUMN %s;", name, fc.name))
				b.addCol = append(b.addCol, fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s;", name, tc.columnDefSQL()))
			default:
				b.alterCol = append(b.alterCol, alterColumn(name, fc, tc)...)
			}
		}
		for _, tc := range t.cols {
			if f.byName[tc.name] == nil {
				b.addCol = append(b.addCol, fmt.Sprintf("ALTER TABLE %s ADD COLUMN %s;", name, tc.columnDefSQL()))
			}
		}

		for _, cn := range sortedKeys(t.cons) {
			tc := t.cons[cn]
			if fc := f.cons[cn]; fc != nil && fc.def == tc.def {
				continue
			}
			stmt := fmt.Sprintf("ALTER TABLE %s ADD CONSTRAINT %s %s;", name, cn, tc.def)
			if tc.kind == "f" {
				b.addFK = append(b.addFK, stmt)
			} else {
				b.addCon = append(b.addCon, stmt)
			}
		}
		for _, idx := range sortedKeys(t.idx) {
			if f.idx[idx] != t.idx[idx] {
				b.addIdx = append(b.addIdx, t.idx[idx]+";")
			}
		}
	}
	return b
}

// alterColumn handles a column that exists on both sides with the same
// generated-ness.
func alterColumn(table string, f, t *colSnap) []string {
	var out []string
	at := fmt.Sprintf("ALTER TABLE %s ALTER COLUMN %s", table, f.name)

	if f.identity != t.identity {
		switch t.identity {
		case "":
			out = append(out, at+" DROP IDENTITY;")
		case "a":
			if f.identity == "" {
				out = append(out, at+" ADD GENERATED ALWAYS AS IDENTITY;")
			} else {
				out = append(out, at+" SET GENERATED ALWAYS;")
			}
		case "d":
			if f.identity == "" {
				out = append(out, at+" ADD GENERATED BY DEFAULT AS IDENTITY;")
			} else {
				out = append(out, at+" SET GENERATED BY DEFAULT;")
			}
		}
	}
	if f.typ != t.typ {
		out = append(out, fmt.Sprintf("%s TYPE %s USING %s::%s;", at, t.typ, f.name, t.typ))
	}
	if t.generated == "" && t.identity == "" && f.expr != t.expr {
		if t.expr == "" {
			out = append(out, at+" DROP DEFAULT;")
		} else {
			out = append(out, fmt.Sprintf("%s SET DEFAULT %s;", at, t.expr))
		}
	}
	if f.notNull != t.notNull && t.identity == "" {
		if t.notNull {
			out = append(out, at+" SET NOT NULL;")
		} else {
			out = append(out, at+" DROP NOT NULL;")
		}
	}
	return out
}

// plan is the up and down SQL that turns the database snapshot cur into
// the definition (whose own snapshot is want).
type plan struct {
	up, down []string
}

func (p plan) empty() bool { return len(p.up) == 0 }

func (d *Definition) plan(cur, want *snapshot) (plan, error) {
	var shared, missing, extra []string
	for _, name := range want.order {
		if cur.tables[name] != nil {
			shared = append(shared, name)
		}
	}
	defined := map[string]bool{}
	var newTables []*Table
	for _, t := range d.tables {
		defined[t.name] = true
		if cur.tables[t.name] == nil {
			newTables = append(newTables, t)
			missing = append(missing, t.name)
		}
	}
	existing := map[string]bool{}
	for _, name := range cur.order {
		existing[name] = true
		if !defined[name] && !d.ignored(name) {
			extra = append(extra, name)
		}
	}

	creates, err := d.createStatements(newTables, existing)
	if err != nil {
		return plan{}, err
	}

	var p plan
	for _, ext := range d.opts.Extensions {
		if !cur.extensions[ext] {
			p.up = append(p.up, fmt.Sprintf("CREATE EXTENSION IF NOT EXISTS %s;", ext))
		}
	}
	upB := diffShared(cur, want, shared)
	p.up = slices.Concat(p.up, upB.pre(), upB.post(), creates, upB.addFK)
	for _, name := range extra {
		p.up = append(p.up, fmt.Sprintf(
			"-- REVIEW: table %s is in the database but no model describes it.\n-- DROP TABLE %s;", name, name))
	}

	downB := diffShared(want, cur, shared)
	p.down = append(p.down, downB.dropFK...)
	if len(missing) > 0 {
		slices.Reverse(missing)
		p.down = append(p.down, fmt.Sprintf("DROP TABLE IF EXISTS %s;", strings.Join(missing, ", ")))
	}
	p.down = slices.Concat(p.down, downB.dropIdx, downB.dropCon, downB.dropCol, downB.post(), downB.addFK)
	return p, nil
}

func sortedKeys[V any](m map[string]V) []string {
	keys := make([]string, 0, len(m))
	for k := range m {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	return keys
}

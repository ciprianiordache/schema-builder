// ErrNoChanges is returned by Generate when the migrations already match
// the definition.
var ErrNoChanges = errors.New("schema: migrations already match the models")

// DriftError is returned by Verify. Statements is the SQL that would bring
// the database in line with the definition.
type DriftError struct {
	Statements []string
}

func (e *DriftError) Error() string {
	return "schema: database and models differ; to match the models the database needs:\n" +
		strings.Join(e.Statements, "\n")
}

// Verify compares the database's current schema (current_schema()) with the
// definition and returns a *DriftError listing every difference in tables,
// columns, constraints and indexes. Functions, triggers and views are not
// compared - they are hand-written SQL.
//
// It builds the definition in a scratch schema inside a transaction that
// is always rolled back, so it never changes the database.
func Verify(ctx context.Context, db *sql.DB, def *Definition) error {
	if err := def.Err(); err != nil {
		return err
	}
	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return fmt.Errorf("schema: verify: begin: %w", err)
	}
	defer tx.Rollback()

	var ns, path string
	if err := tx.QueryRowContext(ctx, `SELECT current_schema(), current_setting('search_path')`).Scan(&ns, &path); err != nil {
		return fmt.Errorf("schema: verify: %w", err)
	}
	cur, err := readSnapshot(ctx, tx, ns)
	if err != nil {
		return err
	}
	want, err := def.build(ctx, tx, path)
	if err != nil {
		return err
	}
	p, err := def.plan(cur, want)
	if err != nil {
		return err
	}
	if !p.empty() {
		return &DriftError{Statements: p.up}
	}
	return nil
}

var migrationName = regexp.MustCompile(`^[a-z0-9_]+$`)

// Generate writes the next migration into dir: the SQL that takes a schema
// built from dir's existing migrations to the definition. It returns the
// paths of the new up and down files, or ErrNoChanges.
//
// The existing migrations and the definition are each applied to a scratch
// schema in a transaction that is rolled back, so db is only borrowed: any
// PostgreSQL database works, applied migrations or not.
//
// Review the output before committing it. A rename shows up as a drop plus
// an add, and hand-written SQL (functions, triggers, views) is added by hand
// below the generated statements.
func Generate(ctx context.Context, db *sql.DB, def *Definition, dir, name string) (upPath, downPath string, err error) {
	if !migrationName.MatchString(name) {
		return "", "", fmt.Errorf("schema: migration name %q must match %s", name, migrationName)
	}
	if err := def.Err(); err != nil {
		return "", "", err
	}
	migs, err := LoadMigrations(os.DirFS(dir))
	if err != nil {
		return "", "", err
	}

	tx, err := db.BeginTx(ctx, nil)
	if err != nil {
		return "", "", fmt.Errorf("schema: generate: begin: %w", err)
	}
	defer tx.Rollback()

	var path string
	if err := tx.QueryRowContext(ctx, `SELECT current_setting('search_path')`).Scan(&path); err != nil {
		return "", "", fmt.Errorf("schema: generate: %w", err)
	}
	before, err := readExtensions(ctx, tx)
	if err != nil {
		return "", "", err
	}
	applied, err := scratchSchema(ctx, tx, path)
	if err != nil {
		return "", "", err
	}
	for _, m := range migs {
		if _, err := tx.ExecContext(ctx, m.Up); err != nil {
			return "", "", fmt.Errorf("schema: generate: replay %04d_%s: %w", m.Version, m.Name, err)
		}
	}
	cur, err := readSnapshot(ctx, tx, applied)
	if err != nil {
		return "", "", err
	}
	// Extensions are database-wide, so one this database already had says
	// nothing about the migrations. Count only those the migrations create.
	for ext := range cur.extensions {
		if before[ext] && !createsExtension(migs, ext) {
			delete(cur.extensions, ext)
		}
	}
	// Types the migrations created (extensions, domains) stay visible to the
	// definition's scratch schema through the search path.
	want, err := def.build(ctx, tx, applied+", "+path)
	if err != nil {
		return "", "", err
	}
	p, err := def.plan(cur, want)
	if err != nil {
		return "", "", err
	}
	if p.empty() {
		return "", "", ErrNoChanges
	}

	var version int64 = 1
	if len(migs) > 0 {
		version = migs[len(migs)-1].Version + 1
	}
	base := filepath.Join(dir, fmt.Sprintf("%04d_%s", version, name))
	upPath, downPath = base+".up.sql", base+".down.sql"

	up := "-- Code generated by schema-builder from the models. Review it before\n" +
		"-- committing; hand-written SQL (functions, triggers, views) goes below.\n\n" +
		strings.Join(p.up, "\n\n") + "\n"
	down := "-- Code generated by schema-builder. Hand-written objects that depend on\n" +
		"-- these tables (views, functions) are dropped above this line.\n\n" +
		strings.Join(p.down, "\n\n") + "\n"

	if err := writeNew(upPath, up); err != nil {
		return "", "", err
	}
	if err := writeNew(downPath, down); err != nil {
		_ = os.Remove(upPath)
		return "", "", err
	}
	return upPath, downPath, nil
}

// createsExtension reports whether any migration runs CREATE EXTENSION ext.
func createsExtension(migs []Migration, ext string) bool {
	re := regexp.MustCompile(`(?i)\bcreate\s+extension\s+(if\s+not\s+exists\s+)?"?` + regexp.QuoteMeta(ext) + `"?(\s|;|$)`)
	for _, m := range migs {
		if re.MatchString(m.Up) {
			return true
		}
	}
	return false
}

// build creates the definition in a fresh scratch schema (search path:
// scratch first, then path) and snapshots it.
func (d *Definition) build(ctx context.Context, tx *sql.Tx, path string) (*snapshot, error) {
	ns, err := scratchSchema(ctx, tx, path)
	if err != nil {
		return nil, err
	}
	stmts, err := d.SQL()
	if err != nil {
		return nil, err
	}
	for _, ext := range d.opts.Extensions {
		stmts = append([]string{"CREATE EXTENSION IF NOT EXISTS " + ext}, stmts...)
	}
	for _, stmt := range stmts {
		if _, err := tx.ExecContext(ctx, stmt); err != nil {
			return nil, fmt.Errorf("schema: the models do not build: %w\n%s", err, stmt)
		}
	}
	return readSnapshot(ctx, tx, ns)
}

// scratchSchema creates an empty, uniquely named schema and puts it first
// on the transaction's search path.
func scratchSchema(ctx context.Context, tx *sql.Tx, path string) (string, error) {
	b := make([]byte, 6)
	if _, err := rand.Read(b); err != nil {
		return "", err
	}
	ns := "schema_builder_" + hex.EncodeToString(b)
	if _, err := tx.ExecContext(ctx, "CREATE SCHEMA "+ns); err != nil {
		return "", fmt.Errorf("schema: create scratch schema: %w", err)
	}
	if _, err := tx.ExecContext(ctx, "SET LOCAL search_path TO "+ns+", "+path); err != nil {
		return "", fmt.Errorf("schema: set search_path: %w", err)
	}
	return ns, nil
}

func writeNew(path, content string) error {
	f, err := os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_EXCL, 0o644)
	if err != nil {
		return fmt.Errorf("schema: write %s: %w", path, err)
	}
	if _, err := f.WriteString(content); err != nil {
		f.Close()
		return fmt.Errorf("schema: write %s: %w", path, err)
	}
	return f.Close()
}
